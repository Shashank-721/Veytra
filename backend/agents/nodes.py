from backend.tools.database import get_database_health


class Hypothesis(BaseModel):
    cause: str
    confidence: float
    supporting_evidence: list[str]


class HypothesisEvaluation(BaseModel):
    hypothesis: str
    supported: bool
    reason: str


# First node in the investigation workflow.
# Its job is to move an OPEN incident into the
# INVESTIGATING state.
def start_investigation(state: InvestigationState):

    # Update the incident status to indicate that
    # Veytra has started investigating the incident.
    state["status"] = "INVESTIGATING"

    # Return the updated state so LangGraph can pass
    # it to the next node.
    return state


# Collect service metrics as the first piece of
# operational evidence for the investigation.
def collect_metrics(state: InvestigationState):

    # Fetch metrics for the service involved in the incident.
    metrics = get_service_metrics(state["service"])

    # Store the metrics in the shared evidence list.
    state["evidence"].append({
        "type": "metrics",
        "data": metrics,
    })

    # Return the updated state to the next LangGraph node.
    return state


